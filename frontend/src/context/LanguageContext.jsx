const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(() => {
    return localStorage.getItem('civicguide_lang') || 'en';
  });

  const setLanguage = (lang) => {
    setLanguageState(lang);
    localStorage.setItem('civicguide_lang', lang);
  };

  const t = (key) => {
    const langDict = baseTranslations[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    // Fallback to Hindi if available and not English, or English
    if (baseTranslations.hi && baseTranslations.hi[key] && language !== 'en') {
      return baseTranslations.hi[key];
    }
    return baseTranslations.en[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, languages: INDIAN_LANGUAGES_LIST }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
