def t(key, lang_code=None, default=None):
    """
    Look up translation string by key with multi-tiered fallback:
    selected language -> Kannada/Hindi if non-English -> English -> default -> key
    """
    if lang_code is None:
        lang_code = "en"
        
    lang_dict = TRANSLATIONS.get(lang_code, {})
    if key in lang_dict:
        return lang_dict[key]
        
    # Tier 2: Check Kannada if code is kn or south Indian, or Hindi
    if lang_code != "en":
        if "kn" in TRANSLATIONS and key in TRANSLATIONS["kn"]:
            # fallback to Kannada for south
            pass
        if "hi" in TRANSLATIONS and key in TRANSLATIONS["hi"]:
            return TRANSLATIONS["hi"][key]
            
    # Tier 3: English fallback
    en_dict = TRANSLATIONS.get("en", {})
    if key in en_dict:
        return en_dict[key]
        
    return default if default is not None else key
